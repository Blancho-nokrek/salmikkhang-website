-- Salmikkhang Community features: accounts, role dropdown, invitation passcodes, requests, member directory and group chat.
-- Run the whole script in Supabase SQL Editor. This does not change the existing homepage content.
create extension if not exists pgcrypto with schema extensions;

create table if not exists public.community_roles (
  id uuid primary key default gen_random_uuid(),
  name text not null unique,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);
create unique index if not exists community_roles_name_lower_uidx on public.community_roles (lower(name));
insert into public.community_roles(name,is_active) values
 ('Member',true),('Volunteer',true),('Coordinator',true),('Admin',true)
on conflict (name) do nothing;

create table if not exists public.community_accounts (
  user_id uuid primary key references auth.users(id) on delete cascade,
  member_id text not null unique,
  full_name text not null,
  role_id uuid references public.community_roles(id) on delete set null,
  role_name text not null default 'Member',
  account_type text not null default 'member' check (account_type in ('member','admin')),
  photo_url text,
  status text not null default 'active' check (status in ('active','disabled')),
  must_change_password boolean not null default true,
  created_at timestamptz not null default now()
);
create unique index if not exists community_accounts_member_id_lower_uidx on public.community_accounts (lower(member_id));

create table if not exists public.community_invites (
  id uuid primary key default gen_random_uuid(),
  label text not null default 'Community invitation',
  code_hash text not null unique,
  uses_limit integer not null default 1 check(uses_limit between 1 and 500),
  uses_count integer not null default 0 check(uses_count >= 0),
  expires_at timestamptz,
  is_active boolean not null default true,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.community_join_requests (
  id uuid primary key default gen_random_uuid(),
  full_name text not null,
  role_id uuid references public.community_roles(id) on delete set null,
  role_name text not null,
  note text,
  invite_id uuid references public.community_invites(id) on delete set null,
  status text not null default 'pending' check(status in ('pending','approved','rejected')),
  created_at timestamptz not null default now(),
  reviewed_at timestamptz,
  reviewed_by uuid references auth.users(id) on delete set null
);

create table if not exists public.community_messages (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.community_accounts(user_id) on delete cascade,
  sender_name text not null,
  sender_role text not null,
  sender_photo text,
  body text not null check (char_length(body) between 1 and 2000),
  created_at timestamptz not null default now()
);
create index if not exists community_messages_created_idx on public.community_messages(created_at desc);
alter table public.community_messages replica identity full;

create or replace function public.is_community_admin()
returns boolean language sql stable security definer set search_path=public,pg_temp
as $$ select exists(select 1 from public.community_accounts a where a.user_id=auth.uid() and a.account_type='admin' and a.status='active') $$;
create or replace function public.is_active_community_member()
returns boolean language sql stable security definer set search_path=public,pg_temp
as $$ select exists(select 1 from public.community_accounts a where a.user_id=auth.uid() and a.status='active') $$;

alter table public.community_roles enable row level security;
alter table public.community_accounts enable row level security;
alter table public.community_invites enable row level security;
alter table public.community_join_requests enable row level security;
alter table public.community_messages enable row level security;

drop policy if exists "Public can see active community roles" on public.community_roles;
create policy "Public can see active community roles" on public.community_roles for select to anon,authenticated using (is_active=true or public.is_community_admin());
drop policy if exists "Admins manage community roles" on public.community_roles;
create policy "Admins manage community roles" on public.community_roles for all to authenticated using(public.is_community_admin()) with check(public.is_community_admin());

drop policy if exists "Members read own account" on public.community_accounts;
create policy "Members read own account" on public.community_accounts for select to authenticated using(user_id=auth.uid() or public.is_community_admin());
drop policy if exists "Admins update community accounts" on public.community_accounts;
create policy "Admins update community accounts" on public.community_accounts for update to authenticated using(public.is_community_admin()) with check(public.is_community_admin());

drop policy if exists "Admins manage community invites" on public.community_invites;
create policy "Admins manage community invites" on public.community_invites for all to authenticated using(public.is_community_admin()) with check(public.is_community_admin());
drop policy if exists "Admins manage join requests" on public.community_join_requests;
create policy "Admins manage join requests" on public.community_join_requests for all to authenticated using(public.is_community_admin()) with check(public.is_community_admin());
drop policy if exists "Active members read chat history" on public.community_messages;
create policy "Active members read chat history" on public.community_messages for select to authenticated using(public.is_active_community_member());
-- Sending and deleting messages are intentionally only through protected RPC functions.

grant usage on schema public to anon, authenticated;
grant select on public.community_roles to anon, authenticated;
grant select on public.community_accounts to authenticated;
grant select on public.community_invites,public.community_join_requests to authenticated;
grant select on public.community_messages to authenticated;
grant usage,select on sequence public.community_messages_id_seq to authenticated;

create or replace function public.get_public_roles()
returns table(id uuid,name text,is_active boolean)
language sql stable security definer set search_path=public,pg_temp
as $$ select r.id,r.name,r.is_active from public.community_roles r where r.is_active=true or public.is_community_admin() order by case when lower(r.name)='member' then 0 when lower(r.name)='volunteer' then 1 when lower(r.name)='coordinator' then 2 when lower(r.name)='admin' then 99 else 50 end, r.name $$;

grant execute on function public.get_public_roles() to anon,authenticated;
grant execute on function public.is_community_admin() to anon,authenticated;
grant execute on function public.is_active_community_member() to authenticated;

create or replace function public.join_community_with_code(p_name text,p_role text,p_passcode text,p_note text default null)
returns jsonb language plpgsql security definer set search_path=public,extensions,pg_temp
as $$
declare v_role public.community_roles%rowtype; v_invite public.community_invites%rowtype; v_request uuid;
begin
  if length(trim(coalesce(p_name,''))) not between 2 and 100 then raise exception 'Please enter a name between 2 and 100 characters.'; end if;
  if length(trim(coalesce(p_passcode,''))) not between 4 and 80 then raise exception 'Invalid or expired invitation passcode.'; end if;
  select * into v_role from public.community_roles where lower(name)=lower(trim(p_role)) and is_active=true limit 1;
  if not found or lower(v_role.name)='admin' then raise exception 'This role cannot be requested.'; end if;
  select * into v_invite from public.community_invites where code_hash=encode(extensions.digest(lower(trim(p_passcode)),'sha256'),'hex') and is_active=true and uses_count<uses_limit and (expires_at is null or expires_at>now()) for update;
  if not found then raise exception 'Invalid or expired invitation passcode.'; end if;
  insert into public.community_join_requests(full_name,role_id,role_name,note,invite_id) values(trim(p_name),v_role.id,v_role.name,nullif(left(trim(coalesce(p_note,'')),500),''),v_invite.id) returning id into v_request;
  update public.community_invites set uses_count=uses_count+1 where id=v_invite.id;
  return jsonb_build_object('request_id',v_request,'status','pending');
end $$;
grant execute on function public.join_community_with_code(text,text,text,text) to anon,authenticated;

create or replace function public.get_public_members()
returns table(full_name text,role_name text,photo_url text)
language sql stable security definer set search_path=public,pg_temp
as $$ select a.full_name,a.role_name,a.photo_url from public.community_accounts a where a.status='active' order by a.full_name $$;
grant execute on function public.get_public_members() to anon,authenticated;

create or replace function public.get_chat_history()
returns table(id bigint,sender_user_id uuid,sender_name text,sender_role text,sender_photo text,body text,created_at timestamptz)
language plpgsql stable security definer set search_path=public,pg_temp
as $$ begin
  if not public.is_active_community_member() then raise exception 'Active member login required.'; end if;
  return query select recent.id,recent.user_id,recent.sender_name,recent.sender_role,recent.sender_photo,recent.body,recent.created_at from (select m.id,m.user_id,m.sender_name,m.sender_role,m.sender_photo,m.body,m.created_at from public.community_messages m order by m.created_at desc limit 200) recent order by recent.created_at asc;
end $$;
grant execute on function public.get_chat_history() to authenticated;

create or replace function public.send_community_message(p_body text)
returns bigint language plpgsql security definer set search_path=public,pg_temp
as $$ declare v_account public.community_accounts%rowtype; v_id bigint; v_body text:=trim(coalesce(p_body,''));
begin
  select * into v_account from public.community_accounts where user_id=auth.uid() and status='active';
  if not found then raise exception 'Active member login required.'; end if;
  if length(v_body) not between 1 and 2000 then raise exception 'Message must be between 1 and 2000 characters.'; end if;
  insert into public.community_messages(user_id,sender_name,sender_role,sender_photo,body) values(auth.uid(),v_account.full_name,v_account.role_name,v_account.photo_url,v_body) returning id into v_id;
  return v_id;
end $$;
grant execute on function public.send_community_message(text) to authenticated;

create or replace function public.admin_delete_community_message(p_message_id bigint)
returns void language plpgsql security definer set search_path=public,pg_temp
as $$ begin if not public.is_community_admin() then raise exception 'Admin permission required.'; end if; delete from public.community_messages where id=p_message_id; end $$;
grant execute on function public.admin_delete_community_message(bigint) to authenticated;

create or replace function public.admin_create_invite(p_label text default 'Community invitation',p_uses_limit integer default 1,p_expires_in_days integer default 7)
returns jsonb language plpgsql security definer set search_path=public,extensions,pg_temp
as $$ declare v_code text; v_id uuid; v_exp timestamptz;
begin
  if not public.is_community_admin() then raise exception 'Admin permission required.'; end if;
  if coalesce(p_uses_limit,0) not between 1 and 500 then raise exception 'Uses must be between 1 and 500.'; end if;
  if coalesce(p_expires_in_days,0) not between 1 and 365 then raise exception 'Expiry must be between 1 and 365 days.'; end if;
  v_code:='SMK-'||upper(encode(extensions.gen_random_bytes(10),'hex')); v_exp:=now()+make_interval(days=>p_expires_in_days);
  insert into public.community_invites(label,code_hash,uses_limit,expires_at,created_by) values(left(coalesce(nullif(trim(p_label),''),'Community invitation'),100),encode(extensions.digest(lower(v_code),'sha256'),'hex'),p_uses_limit,v_exp,auth.uid()) returning id into v_id;
  return jsonb_build_object('id',v_id,'code',v_code,'uses_limit',p_uses_limit,'expires_at',v_exp);
end $$;
grant execute on function public.admin_create_invite(text,integer,integer) to authenticated;

create or replace function public.admin_revoke_invite(p_invite_id uuid)
returns void language plpgsql security definer set search_path=public,pg_temp
as $$ begin
  if not public.is_community_admin() then raise exception 'Admin permission required.'; end if;
  update public.community_invites set is_active=false where id=p_invite_id;
  if not found then raise exception 'Invitation not found.'; end if;
end $$;
grant execute on function public.admin_revoke_invite(uuid) to authenticated;

create or replace function public.admin_create_role(p_name text)
returns uuid language plpgsql security definer set search_path=public,pg_temp
as $$ declare v_id uuid; v_name text:=trim(coalesce(p_name,''));
begin
  if not public.is_community_admin() then raise exception 'Admin permission required.'; end if;
  if length(v_name) not between 2 and 40 then raise exception 'Role name must be 2–40 characters.'; end if;
  if lower(v_name)='admin' then raise exception 'Admin is a protected system role.'; end if;
  if exists(select 1 from public.community_roles where lower(name)=lower(v_name)) then raise exception 'This role already exists.'; end if;
  insert into public.community_roles(name,is_active) values(v_name,true) returning id into v_id; return v_id;
end $$;
grant execute on function public.admin_create_role(text) to authenticated;

create or replace function public.admin_toggle_role(p_role_id uuid,p_is_active boolean)
returns void language plpgsql security definer set search_path=public,pg_temp
as $$ declare v_name text;
begin
  if not public.is_community_admin() then raise exception 'Admin permission required.'; end if;
  select name into v_name from public.community_roles where id=p_role_id;
  if not found then raise exception 'Role not found.'; end if;
  if lower(v_name)='admin' and not p_is_active then raise exception 'The Admin role cannot be disabled.'; end if;
  update public.community_roles set is_active=p_is_active where id=p_role_id;
end $$;
grant execute on function public.admin_toggle_role(uuid,boolean) to authenticated;

create or replace function public.admin_review_join_request(p_request_id uuid,p_decision text)
returns void language plpgsql security definer set search_path=public,pg_temp
as $$ begin
  if not public.is_community_admin() then raise exception 'Admin permission required.'; end if;
  if p_decision not in ('approved','rejected') then raise exception 'Decision must be approved or rejected.'; end if;
  update public.community_join_requests set status=p_decision,reviewed_at=now(),reviewed_by=auth.uid() where id=p_request_id and status='pending';
  if not found then raise exception 'Pending request not found.'; end if;
end $$;
grant execute on function public.admin_review_join_request(uuid,text) to authenticated;

create or replace function public.admin_set_account_status(p_user_id uuid,p_status text)
returns void language plpgsql security definer set search_path=public,pg_temp
as $$ begin
  if not public.is_community_admin() then raise exception 'Admin permission required.'; end if;
  if p_status not in ('active','disabled') then raise exception 'Invalid account status.'; end if;
  if p_user_id=auth.uid() and p_status='disabled' then raise exception 'You cannot disable your own active admin account.'; end if;
  update public.community_accounts set status=p_status where user_id=p_user_id;
  if not found then raise exception 'Account not found.'; end if;
end $$;
grant execute on function public.admin_set_account_status(uuid,text) to authenticated;

create or replace function public.complete_password_change()
returns void language plpgsql security definer set search_path=public,pg_temp
as $$ begin
  if not exists(select 1 from public.community_accounts where user_id=auth.uid() and status='active') then raise exception 'Active account required.'; end if;
  update public.community_accounts set must_change_password=false where user_id=auth.uid();
end $$;
grant execute on function public.complete_password_change() to authenticated;

